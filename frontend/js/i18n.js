// Current Active Language Helper
export function getCurrentLang() {
  return localStorage.getItem("swasthya_lang") || "hi"; // Default to Hindi or previous selection
}

export function setLang(lang) {
  localStorage.setItem("swasthya_lang", lang);
  document.documentElement.lang = lang;
  updateDOMTranslations(lang);
}

export function getTranslation(key) {
  const lang = getCurrentLang();
  return translations[lang]?.[key] || translations["en"]?.[key] || key;
}

export function updateDOMTranslations(lang = getCurrentLang()) {
  const elements = document.querySelectorAll("[data-i18n]");
  elements.forEach(el => {
    const key = el.getAttribute("data-i18n");
    const translation = translations[lang]?.[key];
    if (translation) {
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        el.placeholder = translation;
      } else {
        el.textContent = translation;
      }
    }
  });
}

// Expose globally for instant inline script execution
if (typeof window !== 'undefined') {
  window.swasthyaI18nUpdate = updateDOMTranslations;
  window.swasthyaSetLang = setLang;
}
